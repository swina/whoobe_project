#!/usr/bin/env bash
# Try Whoobe on this machine with one command: builds the images, starts the whole stack in Docker (Postgres, Garage as the S3 store,
# the API, the asset service, the gateway, the dashboard and the editor) and prints the address and the login.
#
#   ./try.sh            start (the first time it builds the images: several minutes; the next starts reuse them and take seconds)
#   ./try.sh rebuild    start and build the images again: after you changed the code or ran `git pull` (several minutes)
#   ./try.sh stop       stop the stack, keep the data
#   ./try.sh reset      stop it and delete its data and its settings file (the next start begins from nothing)
#   ./try.sh status     show the containers
#   ./try.sh logs       follow the logs
#
# Needs Docker with Compose and `openssl`. It uses the ports 3000 to 3003 and 3006 (dashboard, gateway, asset service, API, editor),
# 5432 and 9000: stop whatever uses them, or move all of them with TRY_PORT_BASE=3200 ./try.sh (every port moves by the same step).
# Settings and secrets are generated once into `.env.try` (mode 600, git-ignored); this does not touch a `.env` you may have.
# This is an evaluation stack on plain http://localhost: for a real installation see docs/release/operations/creating-workspaces.md.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"
ENVF="$ROOT/.env.try"
PROJECT=whoobe-try

BASE="${TRY_PORT_BASE:-3000}"
[[ "$BASE" =~ ^[0-9]+$ ]] || { echo "TRY_PORT_BASE must be a number" >&2; exit 1; }
STEP=$((BASE - 3000))
P_ADMIN=$((3000 + STEP)); P_GATEWAY=$((3001 + STEP)); P_ASSET=$((3002 + STEP)); P_CORE=$((3003 + STEP)); P_EDITOR=$((3006 + STEP))
P_PG=$((5432 + STEP)); P_S3=$((9000 + STEP))

need() { command -v "$1" >/dev/null 2>&1 || { echo "$1 is required and was not found" >&2; exit 1; }; }
dc() { ENV_FILE="$ENVF" COMPOSE_PROFILES=local-s3 docker compose -p "$PROJECT" --env-file "$ENVF" -f "$ROOT/docker-compose.yml" "$@"; }

write_env() {
  hex() { openssl rand -hex "$1"; }
  local pg; pg="$(hex 16)"
  ( umask 077; cat > "$ENVF" <<ENV
# Generated by try.sh for the evaluation stack. Never reuse these values elsewhere. Delete the file (./try.sh reset) to start again.
TRY_PORT_BASE=${BASE}
WHOOBE_HOSTNAME=localhost
COMPOSE_PROFILES=local-s3
WS_POSTGRES_PORT=${P_PG}
WS_S3_API_PORT=${P_S3}
WS_ADMIN_DASHBOARD_PORT=${P_ADMIN}
WS_GATEWAY_PORT=${P_GATEWAY}
WS_ASSET_PROCESSOR_PORT=${P_ASSET}
WS_CORE_API_PORT=${P_CORE}
WS_WHOOBE_ONE_SPIKE_PORT=${P_EDITOR}

POSTGRES_USER=whoobe
POSTGRES_PASSWORD=${pg}
POSTGRES_DB=whoobe_try
DB_HOST=postgres
DB_PORT=5432
DB_USER=whoobe
DB_PASSWORD=${pg}
DB_NAME=whoobe_try

MIGRATION_SOURCE_ENCRYPTION_KEY=$(hex 32)
GATEWAY_AUTH_ENCRYPTION_KEY=$(hex 32)
SITE_API_KEY_PEPPER=$(hex 32)
DAM_SERVICE_TOKEN=$(hex 24)
TOTP_ENCRYPTION_KEY=$(hex 32)
MAIL_SETTINGS_ENCRYPTION_KEY=$(hex 32)
UPLOAD_TOKEN_SECRET=$(hex 32)
INTEGRATION_SECRETS_ENCRYPTION_KEY=$(hex 32)

S3_ENDPOINT=http://garage:3900
S3_BUCKET=whoobe-cms-try
S3_REGION=us-east-1
S3_ACCESS_KEY_ID=GK$(hex 12)
S3_SECRET_ACCESS_KEY=$(hex 32)
S3_FORCE_PATH_STYLE=true
S3_PUBLIC_BASE_URL=http://localhost:${P_ASSET}/dam-asset
UPLOAD_PUBLIC_BASE_URL=http://localhost:${P_ASSET}

SEED_ADMIN_EMAIL=admin@whoobe.local
SEED_ADMIN_PASSWORD=$(hex 12)

VITE_ASSET_PROCESSOR_URL=http://localhost:${P_ASSET}
VITE_CORE_API_URL=http://localhost:${P_CORE}
VITE_GATEWAY_URL=http://localhost:${P_GATEWAY}
VITE_WHOOBE_ONE_URL=http://localhost:${P_EDITOR}/whoobe-one
VITE_FONT_FAMILIES=Roboto|Open+Sans

GATEWAY_PORT=3001
GATEWAY_CORE_API_URL=http://core-api:3003
GATEWAY_ASSET_PROCESSOR_URL=http://asset-processor:3002
ASSET_PROCESSOR_URL=http://asset-processor:3002
GATEWAY_DEFAULT_RATE_LIMIT_RPS=10
GATEWAY_RATE_LIMIT_BACKEND=memory
LOG_LEVEL=info
LOG_DIR=./logs
ENV
  )
  chmod 600 "$ENVF"
}

get() { grep -E "^$1=" "$ENVF" | head -1 | cut -d= -f2-; }

check_ports() {
  command -v ss >/dev/null 2>&1 || return 0
  local busy=()
  for p in "$P_ADMIN" "$P_GATEWAY" "$P_ASSET" "$P_CORE" "$P_EDITOR" "$P_PG" "$P_S3"; do
    ss -ltn "sport = :$p" 2>/dev/null | grep -q LISTEN && busy+=("$p")
  done
  if [ "${#busy[@]}" -gt 0 ]; then
    echo "These ports are already in use: ${busy[*]}" >&2
    echo "Stop what uses them, or move them all:  TRY_PORT_BASE=3200 ./try.sh" >&2
    exit 1
  fi
}

CMD="${1:-start}"
case "$CMD" in
  start|rebuild)
    need docker; need openssl
    docker compose version >/dev/null 2>&1 || { echo "Docker Compose (the 'docker compose' command) is required" >&2; exit 1; }
    if [ -f "$ENVF" ]; then
      BASE="$(get TRY_PORT_BASE)"; BASE="${BASE:-3000}"; STEP=$((BASE - 3000))
      P_ADMIN=$((3000 + STEP)); P_GATEWAY=$((3001 + STEP)); P_ASSET=$((3002 + STEP)); P_CORE=$((3003 + STEP)); P_EDITOR=$((3006 + STEP))
    else
      check_ports
      write_env
      echo ">>> settings and secrets written to .env.try"
    fi
    BUILD=()
    have_images=1
    for svc in core-api asset-processor gateway admin-dashboard whoobe-one-spike; do
      docker image inspect "${PROJECT}-${svc}" >/dev/null 2>&1 || have_images=0
    done
    if [ "$CMD" = rebuild ] || [ "$have_images" = 0 ]; then
      BUILD=(--build)
      echo ">>> building and starting the stack (building takes several minutes) ..."
    else
      echo ">>> starting the stack with the images already built (./try.sh rebuild after a git pull) ..."
    fi
    dc up -d ${BUILD[@]+"${BUILD[@]}"}   # empty array safe on bash 3.2 (macOS)
    echo ">>> waiting for the API ..."
    ok=0
    for _ in $(seq 1 120); do
      if curl -fsS "http://localhost:${P_CORE}/health" >/dev/null 2>&1; then ok=1; break; fi
      sleep 3
    done
    if [ "$ok" != 1 ]; then
      echo "The API did not answer in time. See: ./try.sh logs" >&2
      exit 1
    fi
    cat <<EOT

  Whoobe is up.

    Dashboard   http://localhost:${P_ADMIN}
    Login       $(get SEED_ADMIN_EMAIL)
    Password    $(get SEED_ADMIN_PASSWORD)

  Stop it:    ./try.sh stop       (keeps your data)
  Start over: ./try.sh reset      (deletes the data and the settings)
  Docs:       https://docs.whoobe.dev
EOT
    ;;
  stop)   need docker; [ -f "$ENVF" ] || { echo "nothing to stop (no .env.try)"; exit 0; }; dc down --remove-orphans ;;
  reset)  need docker; if [ -f "$ENVF" ]; then dc down -v --remove-orphans; rm -f "$ENVF"; echo ">>> data and settings deleted"; else echo "nothing to reset"; fi ;;
  status) need docker; [ -f "$ENVF" ] || { echo "not started yet (no .env.try)"; exit 0; }; dc ps ;;
  logs)   need docker; [ -f "$ENVF" ] || { echo "not started yet (no .env.try)"; exit 0; }; dc logs -f --tail=100 ;;
  *) echo "usage: ./try.sh [start|rebuild|stop|reset|status|logs]" >&2; exit 1 ;;
esac
