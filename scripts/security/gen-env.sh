#!/usr/bin/env bash
# Generates scripts/security/.env.sectest for the throwaway stack: fixed local ports (dev + 100), a disposable DB
# name that satisfies the harness safety rule (`_sec_test`), and fresh random secrets. Git-ignored, mode 0600.
# Usage: gen-env.sh [--force] [--offset N --name SUFFIX] [output-file]   (refuses to overwrite an existing file without --force)
#   --offset N --name b   a SECOND stack for the workspace-isolation tests: every host port +N, DB / bucket / admin
#                         e-mail carry the suffix, and all secrets are different (see stack.sh, SEC_STACK=b)
set -euo pipefail
FORCE=false; OUT=""; OFF=0; NAME=""
while [ $# -gt 0 ]; do case "$1" in
  --force) FORCE=true; shift ;;
  --offset) OFF="$2"; shift 2 ;;
  --name) NAME="$2"; shift 2 ;;
  *) OUT="$1"; shift ;;
esac; done
[[ "$OFF" =~ ^[0-9]+$ ]] || { echo "--offset must be a number" >&2; exit 1; }
[[ -z "$NAME" || "$NAME" =~ ^[a-z0-9]+$ ]] || { echo "--name must be lowercase letters/digits" >&2; exit 1; }
SFX="${NAME:+_$NAME}"; DSFX="${NAME:+-$NAME}"
OUT="${OUT:-$(cd "$(dirname "$0")" && pwd)/.env.sectest${DSFX}}"
if [ -e "$OUT" ] && ! $FORCE; then echo "$OUT exists (use --force to regenerate)" >&2; exit 0; fi
hex() { openssl rand -hex "$1"; }
( umask 077; cat > "$OUT" <<ENV
# Throwaway stack for security/Docker verification. Never reuse these values elsewhere. Generated by gen-env.sh.
# Host ports are the dev ports +100, so it can run next to the dev stack.
WHOOBE_HOSTNAME=localhost
WS_POSTGRES_PORT=$((5532 + OFF))
WS_S3_API_PORT=$((9100 + OFF))
# only with S3_BACKEND=minio:
WS_MINIO_CONSOLE_PORT=$((9101 + OFF))
COMPOSE_PROFILES=local-s3
WS_CORE_API_PORT=$((3103 + OFF))
WS_ASSET_PROCESSOR_PORT=$((3102 + OFF))
WS_ADMIN_DASHBOARD_PORT=$((3100 + OFF))
WS_WHOOBE_ONE_SPIKE_PORT=$((3106 + OFF))
WS_GATEWAY_PORT=$((3101 + OFF))

POSTGRES_USER=sectest
POSTGRES_PASSWORD=$(hex 16)
POSTGRES_DB=whoobe_sec_test${SFX}
DB_HOST=postgres
DB_PORT=5432
DB_USER=sectest
DB_PASSWORD=__DBPASS__
DB_NAME=whoobe_sec_test${SFX}

MIGRATION_SOURCE_ENCRYPTION_KEY=$(hex 32)
GATEWAY_AUTH_ENCRYPTION_KEY=$(hex 32)
SITE_API_KEY_PEPPER=$(hex 32)
DAM_SERVICE_TOKEN=$(hex 24)

S3_ENDPOINT=http://garage:3900
S3_BUCKET=whoobe-cms-sectest${DSFX}
S3_REGION=us-east-1
# Garage's key format (GK + 24 hex / 64 hex); MinIO accepts it as well
S3_ACCESS_KEY_ID=GK$(hex 12)
S3_SECRET_ACCESS_KEY=$(hex 32)
S3_FORCE_PATH_STYLE=true
S3_PUBLIC_BASE_URL=http://localhost:$((3102 + OFF))/dam-asset

SEED_ADMIN_EMAIL=admin@sectest${DSFX}.local
SEED_ADMIN_PASSWORD=$(hex 12)

VITE_ASSET_PROCESSOR_URL=http://localhost:$((3102 + OFF))
VITE_CORE_API_URL=http://localhost:$((3103 + OFF))
VITE_GATEWAY_URL=http://localhost:$((3101 + OFF))
VITE_WHOOBE_ONE_URL=http://localhost:$((3106 + OFF))/whoobe-one
VITE_FONT_FAMILIES=Roboto|Open+Sans

GATEWAY_PORT=3001
GATEWAY_CORE_API_URL=http://core-api:3003
GATEWAY_ASSET_PROCESSOR_URL=http://asset-processor:3002
ASSET_PROCESSOR_URL=http://asset-processor:3002
GATEWAY_DEFAULT_RATE_LIMIT_RPS=10
GATEWAY_RATE_LIMIT_BACKEND=memory
LOG_LEVEL=info
LOG_DIR=./logs

# the harness sets X-Forwarded-For to play different client addresses
TRUST_PROXY=1

# recommended in production: private assets (is_public=false) need a session on /dam-asset

# test-stack limits kept low so the suites can reach them quickly
PUBLIC_SEARCH_RATE_LIMIT_PER_MINUTE=30
PUBLIC_QUERY_RATE_LIMIT_PER_MINUTE=40
AI_RATE_LIMIT_PER_MINUTE=5

# MFA secrets encrypted at rest (test value)
TOTP_ENCRYPTION_KEY=sectest-$(hex 16)

# outgoing-mail credentials encrypted at rest (test value)
MAIL_SETTINGS_ENCRYPTION_KEY=sectest-$(hex 16)
UPLOAD_TOKEN_SECRET=sectest-upload-$(hex 24)
# where a visitor's browser sends the bytes of a file (the asset service of this stack)
UPLOAD_PUBLIC_BASE_URL=http://localhost:$((3102 + OFF))
# the upload tests send many files from one address
UPLOAD_INTENT_RATE_LIMIT_PER_MINUTE=1000
UPLOAD_PUT_RATE_LIMIT_PER_MINUTE=1000
FORM_SUBMIT_RATE_LIMIT_PER_WINDOW=1000
ENV
)
# DB_PASSWORD must equal POSTGRES_PASSWORD
PG="$(grep '^POSTGRES_PASSWORD=' "$OUT" | cut -d= -f2-)"
sed -i "s|^DB_PASSWORD=__DBPASS__|DB_PASSWORD=${PG}|" "$OUT"
chmod 600 "$OUT"
echo "wrote $OUT"
