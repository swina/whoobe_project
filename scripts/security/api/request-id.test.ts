// Correlation id (docs/plans/system/release-0.4-plan.md 3.1): each service keeps a valid X-Request-Id or makes one, sends it back, writes it
// in the audit row, and the gateway passes it on to core-api. nginx's part is in deploy/nginx/_locations.conf.template.
import { describe, it, expect, beforeAll, afterAll } from 'vitest'
import { randomBytes } from 'node:crypto'
import { Client, clientFor } from '../lib/client'
import { ASSET_TARGET, GATEWAY_TARGET } from '../lib/config'

const tag = randomBytes(4).toString('hex')
const cleanup: (() => Promise<unknown>)[] = []
let admin: Client

beforeAll(async () => { admin = await clientFor('admin') })
afterAll(async () => { for (const f of cleanup.reverse()) await f().catch(() => undefined) })

describe('every service answers with the id', () => {
  for (const [name, base] of [['core-api', undefined], ['gateway', GATEWAY_TARGET], ['asset-processor', ASSET_TARGET]] as const) {
    it(`${name}: keeps a valid one, replaces an invalid one, makes one when absent`, async () => {
      const c = new Client(base)
      const id = `sec-rid-${tag}-${name}`
      expect((await c.get('/health', { 'X-Request-Id': id })).headers.get('x-request-id')).toBe(id)

      const bad = (await c.get('/health', { 'X-Request-Id': 'bad id<>' })).headers.get('x-request-id')
      expect(bad).toMatch(/^[0-9a-f-]{36}$/)
      const long = (await c.get('/health', { 'X-Request-Id': 'a'.repeat(101) })).headers.get('x-request-id')
      expect(long).not.toBe('a'.repeat(101))

      const a = (await c.get('/health')).headers.get('x-request-id')
      const b = (await c.get('/health')).headers.get('x-request-id')
      expect(a).toMatch(/^[0-9a-f-]{36}$/)
      expect(a).not.toBe(b)
    })
  }
})

describe('the audit row carries it', () => {
  const auditRow = async (targetId: string, action: string) => {
    const r = await admin.get(`/audit-log?${new URLSearchParams({ targetId, action, limit: '10' })}`)
    expect(r.status, r.text.slice(0, 200)).toBe(200)
    return (r.json.entries as any[])[0]
  }

  it('sent to core-api directly', async () => {
    const id = `sec-rid-${tag}-direct`
    const c = await admin.post('/auth/roles', { name: `ridrole-${tag}`, description: 'request id test', permissionKeys: ['objects:read'] }, { 'X-Request-Id': id })
    expect(c.status, c.text.slice(0, 160)).toBe(201)
    expect(c.headers.get('x-request-id')).toBe(id)
    const roleId = c.json.role.id
    cleanup.push(() => admin.delete(`/auth/roles/${roleId}`))
    expect((await auditRow(roleId, 'role.create'))?.requestId).toBe(id)
  })

  it('generated by core-api when the request had none: the row has the id of the response', async () => {
    const c = await admin.post('/auth/roles', { name: `ridrole2-${tag}`, description: 'request id test', permissionKeys: ['objects:read'] })
    expect(c.status, c.text.slice(0, 160)).toBe(201)
    const roleId = c.json.role.id
    cleanup.push(() => admin.delete(`/auth/roles/${roleId}`))
    const given = c.headers.get('x-request-id')
    expect(given).toMatch(/^[0-9a-f-]{36}$/)
    expect((await auditRow(roleId, 'role.create'))?.requestId).toBe(given)
  })

  it('through the gateway to core-api: the same id at both ends', async () => {
    const id = `sec-rid-${tag}-gateway`
    const gw = admin.forBase(GATEWAY_TARGET)
    const c = await gw.post('/api/internal/auth/roles', { name: `ridrole3-${tag}`, description: 'request id test', permissionKeys: ['objects:read'] }, { 'X-Request-Id': id })
    expect(c.status, c.text.slice(0, 160)).toBe(201)
    expect(c.headers.get('x-request-id')).toBe(id)
    const roleId = c.json.role.id
    cleanup.push(() => admin.delete(`/auth/roles/${roleId}`))
    expect((await auditRow(roleId, 'role.create'))?.requestId).toBe(id)
  })
})
